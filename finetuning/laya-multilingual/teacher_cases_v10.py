from __future__ import annotations

from dataclasses import dataclass


def cmd(executable: str, *args: str, cwd: str = "/work/project", network: bool = False) -> dict:
    return {"executable": executable, "args": list(args), "cwd": cwd,
            "scope": "workspace", "network": network}


